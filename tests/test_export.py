    # ── push batching ──
    def test_export_push_batched(self):
        self.start_push_mode(600)
        counts = []
        for n in (1, 2, 3):
            self.change(n)
            self.tick_export()
            counts.append(int(git("rev-list", "--count", "refs/heads/state", cwd=self.bare)) if self.remote_state() else 0)
        # the first export pushes (no push yet); the next two stay local within the interval
        self.assertEqual(counts, [1, 1, 1])
        self.assertEqual(self.state_commits(), 3)

    def test_export_push_after_interval(self):
        self.start_push_mode(0)
        for n in (1, 2, 3):
            self.change(n)
            self.tick_export()
            self.assertEqual(self.remote_state(), self.local_state())
            self.assertEqual(int(git("rev-list", "--count", "refs/heads/state", cwd=self.bare)), n)

    def test_export_manual_pushes_now(self):
        self.start_push_mode(600)
