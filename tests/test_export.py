    # ── helpers ──
    def start_push_mode(self, interval):
        h = self.env.home_dir
        git("commit", "-q", "--allow-empty", "-m", "base", cwd=h)
        git("push", "-q", "-u", "origin", "main", cwd=h)
        self.ok("config", "git_push", "1")
        self.ok("config", "push_interval_s", str(interval))

    def change(self, n):
        self.ok("plan", "G-001", f"zz-test plan change {n}", agent="zz-test-director")

    def tick_export(self):
        self.ok("tick")

    def remote_state(self):
        r = subprocess.run(["git", "rev-parse", "-q", "--verify", "refs/heads/state"], cwd=self.bare,
                           capture_output=True, text=True)
        return r.stdout.strip()

    def local_state(self):
        return git("rev-parse", "refs/heads/state", cwd=self.env.home_dir)

    def state_commits(self):
        return git("log", "--format=%s", "refs/heads/state", cwd=self.env.home_dir).count("state: ")

    def main_heads(self):
        return git("rev-parse", "main", cwd=self.env.home_dir), git("rev-parse", "main", cwd=self.bare)

    def other(self):
        """A second clone of origin, to play 'someone merged a PR'."""
        other = self.env.home / "other"
        if not other.exists():
            git("clone", "-q", "-b", "main", str(self.bare), str(other), cwd=self.env.home)
        else:
            git("pull", "-q", "--ff-only", cwd=other)
        return other

    def merge_code(self, name="bin/x", body="code\n"):
        other = self.other()
        (other / name).parent.mkdir(exist_ok=True)
        (other / name).write_text(body)
        git("add", name, cwd=other)
        git("commit", "-q", "-m", f"code {name}", cwd=other)
        git("push", "-q", "origin", "main", cwd=other)

    def track_exports(self):
        """Phase A shape: exports/ and state/ are tracked on main."""
        h = self.env.home_dir
        self.ok("export", "--no-push")
        git("add", "exports", "state", cwd=h)
        git("commit", "-q", "-m", "track generated files", cwd=h)
        git("push", "-q", "origin", "main", cwd=h)

    def old_state_commit(self, tag):
        """What the old export() did: a 'state:' commit of the generated files on main."""
        h = self.env.home_dir
        with open(h / "exports" / "INDEX.md", "a") as f:  # not export(): the new code would migrate right here
            f.write(f"old tick {tag}\n")
        git("add", "exports", "state", cwd=h)
        git("commit", "-q", "-m", f"state: old {tag}", cwd=h)

    def sync_events(self):
        return self.env.sql("SELECT detail FROM events WHERE action='sync-failed'")

    def director_msgs(self):
        return self.env.sql("SELECT subject FROM messages WHERE subject LIKE 'state sync failed%'")

    def migrated(self):
        return [json.loads(r["detail"]) for r in self.env.sql("SELECT detail FROM events WHERE action='state-migrated'")]

    # ── the state branch ──
    def test_export_commits_to_state_branch_and_pushes(self):
        self.start_push_mode(0)
        h = self.env.home_dir
        main_before = self.main_heads()
        self.change(1)
        self.tick_export()
        self.assertRegex(git("log", "-1", "--format=%s", "refs/heads/state", cwd=h), r"^state: ")
        names = git("ls-tree", "-r", "--name-only", "refs/heads/state", cwd=h).splitlines()
        self.assertTrue(names)
        self.assertTrue(all(n.startswith(("exports/", "state/")) for n in names), names)
        self.assertEqual(self.remote_state(), self.local_state())
        self.assertEqual(self.main_heads(), main_before)
        self.assertEqual(git("log", "--format=%s", "main", cwd=h), "base")

    def test_export_no_change_no_new_state_commit(self):
        self.start_push_mode(0)
        self.tick_export()
        # a tick itself may log events; make the exported files settle first
        self.tick_export()
        n = self.state_commits()
        tip = self.local_state()
        self.ok("export")
        self.assertEqual(self.state_commits(), n)
        self.assertEqual(self.local_state(), tip)

    def test_export_commits_only_state(self):
        self.start_push_mode(0)
        h = self.env.home_dir
        (h / "foo").write_text("unrelated\n")
        git("add", "foo", cwd=h)
        head = git("rev-parse", "HEAD", cwd=h)
        self.change(1)
        self.tick_export()
        names = git("ls-tree", "-r", "--name-only", "refs/heads/state", cwd=h).splitlines()
        self.assertTrue(names)
        self.assertTrue(all(n.startswith(("exports/", "state/")) for n in names), names)
        self.assertEqual(git("diff", "--cached", "--name-only", cwd=h), "foo")
        self.assertEqual(git("rev-parse", "HEAD", cwd=h), head)

    def test_first_run_continues_origin_state(self):
        self.start_push_mode(0)
        other = self.other()
        git("checkout", "-q", "--orphan", "state", cwd=other)
        git("read-tree", "--empty", cwd=other)
        (other / "exports").mkdir()
        (other / "exports" / "old.md").write_text("old\n")
        git("add", "exports", cwd=other)
        git("commit", "-q", "-m", "state: ancient", cwd=other)
        git("push", "-q", "origin", "state", cwd=other)
        ancient = git("rev-parse", "HEAD", cwd=other)
        self.change(1)
        self.tick_export()
        self.assertEqual(git("rev-parse", "refs/heads/state~1", cwd=self.env.home_dir), ancient)
