    def test_export_idle_pushes_after_interval(self):
        self.start_push_mode(600)
        self.change(1)
        self.tick_export()
        self.change(2)
        self.tick_export()  # batched: committed, not pushed
        self.assertNotEqual(self.remote_state(), self.local_state())
        self.tick_export()  # idle, interval not passed
        self.assertNotEqual(self.remote_state(), self.local_state())
        self.env.sql("UPDATE config SET value='0' WHERE key='last_push_ts'")
        self.tick_export()  # idle, interval passed
        self.assertEqual(self.remote_state(), self.local_state())

    def test_idle_push_failure_logged(self):
        self.start_push_mode(600)
        self.change(1)
        self.tick_export()
        self.change(2)
        self.tick_export()  # committed, batched
        hook = self.bare / "hooks" / "pre-receive"
        hook.write_text("#!/bin/sh\necho nope >&2\nexit 1\n")
        hook.chmod(0o755)
        self.env.sql("UPDATE config SET value='0' WHERE key='last_push_ts'")
        self.tick_export()  # idle push fails
        self.assertEqual(len(self.env.sql("SELECT detail FROM events WHERE action='push-failed'")), 1)
        self.env.sql("UPDATE config SET value='0' WHERE key='last_push_ts'")
        self.tick_export()  # throttled
        self.assertEqual(len(self.env.sql("SELECT detail FROM events WHERE action='push-failed'")), 1)
        self.assertEqual(self.director_msgs(), [])

