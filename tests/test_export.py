    # ── end to end: old tick → PR A lands → new tick → PR B lands → new tick ──
    def test_cutover_simulation(self):
        self.start_push_mode(0)
        h = self.env.home_dir
        self.track_exports()
        # 1. old behaviour: some state commits pushed, some not
        self.old_state_commit(1)
        git("push", "-q", "origin", "main", cwd=h)
        self.old_state_commit(2)
        self.old_state_commit(3)
        # 2. PR A (touches only bin/) lands on origin main
        self.merge_code("bin/factory-pr-a")
        # 3. the old tick: pull --rebase --autostash applies it cleanly
        git("pull", "-q", "--rebase", "--autostash", cwd=h)
        self.assertEqual(git("status", "--porcelain", "--untracked-files=no", cwd=h), "")
        # 4. the new tick
        self.change(4)
        self.tick_export()
        self.assertEqual(self.main_heads()[0], self.main_heads()[1])
        subjects = git("log", "--format=%s", "main", cwd=self.bare)
        self.assertIn("state: old 1", subjects)  # pushed by the old code, already on origin
        self.assertNotIn("state: old 2", subjects)  # the unpushed ones are dropped, not pushed
        self.assertEqual(self.migrated(), [{"commits": 2, "how": "dropped"}])
        self.assertEqual(self.remote_state(), self.local_state())
        # 5. PR B lands: exports/ and state/ leave main
        other = self.other()
        git("rm", "-rq", "--cached", "exports", "state", cwd=other)
        (other / ".gitignore").write_text("/exports/\n/state/\n/run/\nfactory.db*\n/roles\n")
        git("add", ".gitignore", cwd=other)
        git("commit", "-q", "-m", "untrack generated files", cwd=other)
        git("push", "-q", "origin", "main", cwd=other)
        # 6. the next new tick
        self.change(5)
        self.tick_export()
        self.assertEqual(self.main_heads()[0], self.main_heads()[1])
        self.assertEqual(git("ls-files", "exports", "state", cwd=h), "")
        self.assertTrue((h / "exports" / "INDEX.md").exists())
        self.assertTrue((h / "state" / "factory.sql").exists())
        self.assertEqual(git("status", "--porcelain", cwd=h), "")
        self.assertEqual(self.remote_state(), self.local_state())
        self.assertIn("plan change 5", git("show", "refs/heads/state:exports/goals/G-001.md", cwd=h))
        self.assertEqual(self.sync_events(), [])

