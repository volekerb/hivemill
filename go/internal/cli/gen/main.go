// Command gen writes defaults_gen.go from the DEFAULT_CONFIG literal of bin/factory_cli.py (run by go generate in
// go/internal/cli). Pass -check to compare instead of write.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"

	"factory/go/internal/cli/pydefaults"
)

func main() {
	check := flag.Bool("check", false, "fail when defaults_gen.go is not what the generator would write")
	src := flag.String("src", filepath.Join("..", "..", "..", "bin", "factory_cli.py"), "path of factory_cli.py")
	out := flag.String("out", "defaults_gen.go", "output file")
	flag.Parse()
	data, err := os.ReadFile(*src)
	if err != nil {
		fail(err)
	}
	entries, err := pydefaults.Parse(data)
	if err != nil {
		fail(err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate (internal/cli/gen) from the DEFAULT_CONFIG literal of bin/factory_cli.py; DO NOT EDIT.\n\n")
	b.WriteString("package cli\n\n// DefaultConfig lists every config key and its default, in DEFAULT_CONFIG order.\nvar DefaultConfig = []ConfigDefault{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t{%s, %s},\n", strconv.Quote(e.Key), strconv.Quote(e.Value))
	}
	b.WriteString("}\n")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if *check {
		cur, err := os.ReadFile(*out)
		if err != nil || !bytes.Equal(cur, formatted) {
			fail(fmt.Errorf("%s is stale: run `go generate ./internal/cli`", *out))
		}
		return
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
